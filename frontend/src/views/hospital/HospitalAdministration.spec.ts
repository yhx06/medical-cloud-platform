import { describe, expect, it, vi } from 'vitest'
import { mount, flushPromises } from '@vue/test-utils'
import Departments from './DepartmentsView.vue'
import Doctors from './DoctorsView.vue'
import Schedule from './ScheduleSlotsView.vue'
import Statistics from './HospitalStatisticsView.vue'
import Dashboard from '../DashboardView.vue'
import { setupWorkflow, department, doctor, slot, hospitalStats, page } from '../workflowTestSupport'

describe('hospital administration', () => {
  const api = setupWorkflow('HOSPITAL_ADMIN')
  it('shows hospital profile and creates and updates a department with confirmation', async () => {
    api().onGet('/api/hospital/profile').reply(200, { data: { id: 'tenant-a', name: '演示医院', status: 'ACTIVE' } })
    api().onGet('/api/hospital/departments').reply(200, { data: [department] })
    api().onPost('/api/hospital/departments').reply(200, { data: { ...department, id: 'new', name: '儿科' } })
    api().onPut('/api/hospital/departments/department-a').reply(200, { data: { ...department, status: 'DISABLED' } })
    const view = mount(Departments)
    await flushPromises()
    expect(view.text()).toContain('科室管理')
    expect(view.text()).toContain('演示医院')
    await view.get('[name="department-name"]').setValue('儿科')
    await view.get('[data-test="department-form"]').trigger('submit')
    await flushPromises()
    expect(JSON.parse(api().history.post[0]!.data).name).toBe('儿科')
    await view.findAll('[data-test="edit-department"]')[0]!.trigger('click')
    await view.get('[name="department-status"]').setValue('DISABLED')
    await view.get('[data-test="department-form"]').trigger('submit')
    await flushPromises()
    expect(window.confirm).toHaveBeenCalled()
    expect(view.text()).toContain('停用')
  })
  it('creates a doctor under an existing department and confirms account status changes', async () => {
    api().onGet('/api/hospital/departments').reply(200, { data: [department] })
    api().onGet('/api/hospital/doctors').reply(200, { data: [doctor] })
    api().onPost('/api/hospital/doctors').reply(200, { data: { ...doctor, id: 'new' } })
    api().onPut('/api/hospital/doctors/doctor-a/status').reply(200, { data: { ...doctor, status: 'DISABLED' } })
    const view = mount(Doctors)
    await flushPromises()
    await view.get('[name="username"]').setValue('new_doctor')
    await view.get('[name="password"]').setValue('Demo@123456')
    await view.get('[name="displayName"]').setValue('王医生')
    await view.get('[name="departmentId"]').setValue('department-a')
    await view.get('form').trigger('submit')
    await flushPromises()
    expect(JSON.parse(api().history.post[0]!.data)).toMatchObject({ username: 'new_doctor', departmentId: 'department-a', displayName: '王医生' })
    vi.mocked(window.confirm).mockReturnValueOnce(false)
    await view.findAll('[data-test="doctor-status"]')[0]!.trigger('click')
    expect(api().history.put).toHaveLength(0)
    await view.findAll('[data-test="doctor-status"]')[0]!.trigger('click')
    await flushPromises()
    expect(view.text()).toContain('停用')
  })
  it('validates and publishes a slot with numeric capacity and fee', async () => {
    api().onGet('/api/hospital/doctors').reply(200, { data: [doctor] })
    api().onGet('/api/catalog/schedule-slots').reply(200, { data: page() })
    api().onPost('/api/hospital/schedule-slots').reply(200, { data: slot })
    const view = mount(Schedule)
    await flushPromises()
    await view.get('[name="doctorId"]').setValue('doctor-a')
    await view.get('[name="date"]').setValue('2026-10-01')
    await view.get('[name="startTime"]').setValue('10:00')
    await view.get('[name="endTime"]').setValue('09:00')
    await view.get('form').trigger('submit')
    expect(api().history.post).toHaveLength(0)
    await view.get('[name="endTime"]').setValue('11:00')
    await view.get('[name="capacity"]').setValue(3)
    await view.get('[name="fee"]').setValue(25)
    await view.get('form').trigger('submit')
    await flushPromises()
    expect(JSON.parse(api().history.post[0]!.data)).toEqual({ doctorId: 'doctor-a', date: '2026-10-01', startTime: '10:00', endTime: '11:00', capacity: 3, fee: 25 })
    expect(view.text()).toContain('发布成功')
  })
  it('queries only this hospital available catalog slots with server pagination', async () => {
    api().onGet('/api/hospital/doctors').reply(200, { data: [doctor] })
    api().onGet('/api/catalog/schedule-slots').reply(200, { data: page([slot], 0, 11) })
    const view = mount(Schedule)
    await flushPromises()
    expect(api().history.get.find(request => request.url === '/api/catalog/schedule-slots')?.params).toMatchObject({ tenantId: 'tenant-a', page: 0, size: 10 })
    await view.get('[data-test="next-page"]').trigger('click')
    await flushPromises()
    expect(api().history.get.at(-1)?.params).toMatchObject({ tenantId: 'tenant-a', page: 1 })
    expect(view.text()).toContain('李医生')
  })
  it('queries date-range aggregate statistics and renders actual amounts', async () => {
    api().onGet('/api/hospital/statistics').reply(200, { data: hospitalStats })
    const view = mount(Statistics)
    await flushPromises()
    expect(view.text()).toContain('175.00')
    await view.get('[name="from"]').setValue('2026-09-01')
    await view.get('[name="to"]').setValue('2026-09-22')
    await view.get('form').trigger('submit')
    await flushPromises()
    expect(api().history.get.at(-1)?.params).toEqual({ from: '2026-09-01', to: '2026-09-22' })
    const dashboard = mount(Dashboard, { global: { stubs: { RouterLink: true } } })
    await flushPromises()
    expect(dashboard.get('[data-test="metric-appointments"]').text()).toContain('12')
    expect(api().history.get.every(r => r.url?.startsWith('/api/hospital/'))).toBe(true)
  })
})
