import { describe, expect, it, vi } from 'vitest'
import { mount, flushPromises } from '@vue/test-utils'
import Editor from './ConsultationEditorView.vue'
import Appointments from './DoctorAppointmentsView.vue'
import Records from './DoctorRecordsView.vue'
import Dashboard from '../DashboardView.vue'
import { setupWorkflow, appointment, record } from '../workflowTestSupport'
import { useAuthStore } from '../../stores/auth'
import { useConsultationWorkspace } from '../../stores/consultationWorkspace'

describe('doctor consultation workflows', () => {
  const api = setupWorkflow('DOCTOR')
  it('starts only an assigned booked appointment and opens the returned consultation', async () => {
    api().onGet('/api/doctor/appointments').reply(200, { data: [appointment] })
    api().onPost('/api/doctor/appointments/appointment-a/start').reply(200, { data: record })
    api().onGet('/api/records/record-a/files').reply(200, { data: [] })
    const view = mount(Appointments)
    await flushPromises()
    await view.get('[data-test="start-consultation"]').trigger('click')
    await flushPromises()
    expect(view.get('[name="complaint"]').element).toHaveProperty('value', '头痛')
    expect(view.text()).toContain('接诊中')
  })
  it('validates a completion, saves the current form before completing, and freezes the record', async () => {
    api().onGet('/api/records/record-a/files').reply(200, { data: [] })
    api().onPut('/api/doctor/consultations/appointment-a/draft').reply(200, { data: record })
    api().onPost('/api/doctor/consultations/appointment-a/complete').reply(200, { data: { ...record, status: 'COMPLETED' } })
    const view = mount(Editor, { props: { record: { ...record, diagnosis: '' } } })
    await flushPromises()
    await view.get('[data-test="complete-consultation"]').trigger('click')
    expect(api().history.put).toHaveLength(0)
    expect(view.text()).toContain('诊断')
    await view.get('[name="diagnosis"]').setValue('偏头痛')
    await view.get('[data-test="add-prescription"]').trigger('click')
    await view.get('[name="medication-0"]').setValue('演示药')
    await view.get('[name="dosage-0"]').setValue('1片')
    await view.get('[name="frequency-0"]').setValue('每日一次')
    await view.get('[name="duration-0"]').setValue(2)
    await view.get('[data-test="complete-consultation"]').trigger('click')
    await flushPromises()
    expect(JSON.parse(api().history.put[0]!.data)).toEqual({ complaint: '头痛', diagnosis: '偏头痛', advice: '休息', prescriptionItems: [{ medicationName: '演示药', dosage: '1片', frequency: '每日一次', durationDays: 2 }] })
    expect(api().history.post[0]?.url).toBe('/api/doctor/consultations/appointment-a/complete')
    expect(api().history.post[0]?.data).toBeUndefined()
    expect(view.find('[data-test="complete-consultation"]').exists()).toBe(false)
    expect(view.text()).toContain('已完成')
  })
  it('saves draft without creating an order and does not complete when saving fails', async () => {
    api().onGet('/api/records/record-a/files').reply(200, { data: [] })
    api().onPut('/api/doctor/consultations/appointment-a/draft').replyOnce(200, { data: record }).onPut('/api/doctor/consultations/appointment-a/draft').reply(400, { message: '处方不合法' })
    const view = mount(Editor, { props: { record } })
    await flushPromises()
    await view.get('form').trigger('submit')
    await flushPromises()
    expect(view.text()).toContain('草稿已保存')
    await view.get('[data-test="complete-consultation"]').trigger('click')
    await flushPromises()
    expect(api().history.post).toHaveLength(0)
    expect(view.text()).toContain('处方不合法')
  })
  it('only appends a confirmed correction to a completed record', async () => {
    api().onGet('/api/records/record-a/files').reply(200, { data: [] })
    api().onPost('/api/doctor/records/record-a/corrections', { reason: '补充检查说明' }).reply(200, { data: { ...record, status: 'COMPLETED', corrections: [{ id: 'c', sequenceNumber: 1, doctorId: 'doctor-a', reason: '补充检查说明', createdAt: record.createdAt }] } })
    const view = mount(Editor, { props: { record: { ...record, status: 'COMPLETED' } } })
    await flushPromises()
    expect(view.find('[name="diagnosis"]').exists()).toBe(false)
    await view.get('[name="correction"]').setValue('补充检查说明')
    vi.mocked(window.confirm).mockReturnValueOnce(false)
    await view.get('form').trigger('submit')
    expect(api().history.post).toHaveLength(0)
    await view.get('form').trigger('submit')
    await flushPromises()
    expect(view.text()).toContain('补充检查说明')
    expect(api().history.put).toHaveLength(0)
  })
  it('shows upload limits before selection, rejects invalid files and surfaces backend rejection', async () => {
    api().onGet('/api/records/record-a/files').reply(200, { data: [] })
    api().onPost('/api/doctor/records/record-a/files').reply(400, { message: '文件类型不支持' })
    const view = mount(Editor, { props: { record } })
    await flushPromises()
    expect(view.text()).toContain('10 MiB')
    const input = view.get('input[type="file"]')
    expect(input.attributes('accept')).toBe('.pdf,.jpg,.jpeg,.png,application/pdf,image/jpeg,image/png')
    Object.defineProperty(input.element, 'files', { configurable: true, value: [new File(['bad'], 'bad.txt', { type: 'text/plain' })] })
    await input.trigger('change')
    expect(api().history.post).toHaveLength(0)
    expect(view.text()).toContain('PDF')
    Object.defineProperty(input.element, 'files', { configurable: true, value: [new File(['pdf'], '报告.pdf', { type: 'application/pdf' })] })
    await input.trigger('change')
    await flushPromises()
    expect(view.text()).toContain('文件类型不支持')
  })
  it('shows completed appointment history without using a mutation to read missing records', async () => {
    api().onGet('/api/doctor/appointments').reply(200, { data: [{ ...appointment, status: 'COMPLETED' }] })
    const view = mount(Records)
    await flushPromises()
    expect(view.text()).toContain('appointment-a')
    expect(view.text()).toContain('历史病历')
    expect(api().history.post).toHaveLength(0)
    expect(api().history.get.every(r => r.url === '/api/doctor/appointments')).toBe(true)
  })
  it('rejects oversized files before any upload request', async () => {
    api().onGet('/api/records/record-a/files').reply(200, { data: [] })
    const view = mount(Editor, { props: { record } })
    await flushPromises()
    const input = view.get('input[type="file"]')
    const file = new File(['pdf'], 'large.pdf', { type: 'application/pdf' })
    Object.defineProperty(file, 'size', { value: 10 * 1024 * 1024 + 1 })
    Object.defineProperty(input.element, 'files', { value: [file] })
    await input.trigger('change')
    expect(view.text()).toContain('不得超过 10 MiB')
    expect(api().history.post).toHaveLength(0)
  })
  it('retains only own tenant session records and clears them on logout', () => {
    const workspace = useConsultationWorkspace()
    workspace.remember(record)
    workspace.remember({ ...record, id: 'foreign', tenantId: 'tenant-b' })
    workspace.remember({ ...record, id: 'another-doctor', doctorId: 'doctor-b' })
    expect(workspace.records.map(item => item.id)).toEqual(['record-a'])
    useAuthStore().logout()
    expect(workspace.records).toEqual([])
  })
  it('derives doctor dashboard counts from the assigned appointment endpoint', async () => {
    api().onGet('/api/doctor/appointments').reply(200, { data: [appointment, { ...appointment, id: 'active', status: 'IN_PROGRESS' }] })
    const view = mount(Dashboard, { global: { stubs: { RouterLink: true } } })
    await flushPromises()
    expect(view.get('[data-test="metric-appointments"]').text()).toContain('2')
    expect(view.get('[data-test="metric-pending"]').text()).toContain('1')
    expect(api().history.get).toHaveLength(1)
  })
})
